import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const html=readFileSync(new URL("../prototypes/v47/spark-school-attendance.html",import.meta.url),"utf8");
const rules=readFileSync(new URL("../firestore.v47.prototype.rules",import.meta.url),"utf8");
assert.match(html,/name="attendanceDate" id="attendance-date" type="date" required/);
assert.match(html,/const todayLocal=\(\)=>/);
assert.match(html,/d\.getFullYear\(\)/);
assert.match(html,/d\.getMonth\(\)\+1/);
assert.match(html,/d\.getDate\(\)/);
assert.match(html,/const setToday=\(\)=>/);
assert.match(html,/setToday\(\);/);
assert.match(html,/const attendanceDate=String\(fields\.get\("attendanceDate"\)\|\|""\)/);
assert.match(html,/const payload=\{schoolId:id,studentId,classId,term,attendanceDate,present:/);
assert.match(html,/entryForm\.reset\(\);setToday\(\)/);
assert.match(html,/<th>Date<\/th>/);
assert.match(html,/data\.attendanceDate\|\|"—"/);
const shape=rules.slice(rules.indexOf("function attendanceShape(schoolId)"),rules.indexOf("function unchangedMarksIdentity()"));
assert.ok(shape.includes("'attendanceDate'"),"date field permitted by rules");
assert.ok(shape.includes("request.resource.data.attendanceDate is string"),"date type checked");
assert.ok(shape.includes("attendanceDate.matches("),"date format checked");
assert.ok(shape.includes("!('attendanceDate' in request.resource.data)"),"legacy attendance without dates remains readable/updatable");
assert.ok(shape.includes("validTerm(request.resource.data.term)"),"term checks retained");
console.log("V47 attendance date form and Firestore rule contract passed");
