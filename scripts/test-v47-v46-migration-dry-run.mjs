import assert from "node:assert/strict";
import {planV46TenantCopy} from "../src/v47/v46-migration-dry-run.mjs";
import {V46_COLLECTION_POLICY} from "../src/v47/v46-collection-map.mjs";
const collections=Object.fromEntries(Object.keys(V46_COLLECTION_POLICY).map(name=>[name,[]]));
collections.students=[{id:"s1",data:{name:"Student"}}];
collections.marks=[{id:"m1",data:{score:50}}];
collections.user_roles=[{id:"uid1",data:{role:"teacher"}}];
const input={schoolId:"school_A001",collections};
const plan=planV46TenantCopy(input);
assert.equal(plan.totalDocuments,3);
assert.equal(plan.writesPerformed,0);
assert.equal(plan.requiresApproval,true);
assert.equal(plan.entries.find(e=>e.source==="students/s1").destination,"schools/school_A001/students/s1");
assert.equal(plan.entries.find(e=>e.source==="user_roles/uid1").review,true);
assert.notEqual(planV46TenantCopy({...input,schoolId:"school_B001"}).entries[0].destination,plan.entries[0].destination);
assert.throws(()=>planV46TenantCopy({...input,collections:{...collections,students:[{id:"a/b",data:{}}]}}));
assert.throws(()=>planV46TenantCopy({...input,collections:{...collections,students:[{id:"s1",data:{}},{id:"s1",data:{}}]}}),/Duplicate/);
assert.throws(()=>planV46TenantCopy({...input,collections:{...collections,unknown:[]}}));
assert.throws(()=>planV46TenantCopy({...input,collections:{students:[]}}),/Incomplete V46 migration snapshot/);
console.log("V47 migration dry-run contract tests passed");
