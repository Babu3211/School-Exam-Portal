import assert from "node:assert/strict";
import {loadVerifiedSchoolSession} from "../src/v47/verified-school-session.mjs";
const auth={verifyIdToken:async(token,checkRevoked)=>{
 assert.equal(checkRevoked,true);
 if(token==="good")return {uid:"user1",firebase:{sign_in_provider:"password"}};
 if(token==="anonymous")return {uid:"user1",firebase:{sign_in_provider:"anonymous"}};
 if(token==="missingUid")return {firebase:{sign_in_provider:"password"}};
 throw new Error("Invalid token");
}};
const docs=new Map([["schools/school_A001",{status:"active"}],["schools/school_B001",{status:"active"}],["schools/school_A001/members/user1",{active:true,roles:["viewer"]}],["schools/school_B001/members/user2",{active:true,roles:["school_admin"]}]]);
const paths=[];
const firestore={doc:path=>{paths.push(path);return {get:async()=>({exists:docs.has(path),data:()=>docs.get(path)})};}};
const good=await loadVerifiedSchoolSession({idToken:"good",schoolId:"school_A001",auth,firestore});
assert.deepEqual(good.roles,["viewer"]);
await assert.rejects(loadVerifiedSchoolSession({idToken:"good",schoolId:"school_B001",auth,firestore}),/No active membership/);
const pathsBeforeAnonymous=paths.length;
await assert.rejects(loadVerifiedSchoolSession({idToken:"anonymous",schoolId:"school_A001",auth,firestore}),/Authenticated account/);
assert.equal(paths.length,pathsBeforeAnonymous,"Anonymous users must not read school data");
const pathsBeforeMissingUid=paths.length;
await assert.rejects(loadVerifiedSchoolSession({idToken:"missingUid",schoolId:"school_A001",auth,firestore}),/Authenticated account/);
assert.equal(paths.length,pathsBeforeMissingUid,"Missing token UID must not read school data");
const pathsBeforeInvalidToken=paths.length;
await assert.rejects(loadVerifiedSchoolSession({idToken:"bad",schoolId:"school_A001",auth,firestore}),/Invalid token/);
assert.equal(paths.length,pathsBeforeInvalidToken,"Invalid Firebase token must not read Firestore");
docs.set("schools/school_A001/members/user1",{active:true,roles:["viewer"],uid:"otherUser",schoolId:"school_A001"});
await assert.rejects(loadVerifiedSchoolSession({idToken:"good",schoolId:"school_A001",auth,firestore}),/identity mismatch/);
docs.set("schools/school_A001/members/user1",{active:true,roles:["viewer"],uid:"user1",schoolId:"school_B001"});
await assert.rejects(loadVerifiedSchoolSession({idToken:"good",schoolId:"school_A001",auth,firestore}),/identity mismatch/);
docs.set("schools/school_A001/members/user1",{active:true,roles:["viewer"]});
docs.set("schools/school_A001",{status:"suspended"});
await assert.rejects(loadVerifiedSchoolSession({idToken:"good",schoolId:"school_A001",auth,firestore}),/School is not active/);
docs.set("schools/school_A001",{status:"pending"});
await assert.rejects(loadVerifiedSchoolSession({idToken:"good",schoolId:"school_A001",auth,firestore}),/School is not active/);
assert.deepEqual(paths,["schools/school_A001","schools/school_A001/members/user1","schools/school_B001","schools/school_B001/members/user1","schools/school_A001","schools/school_A001/members/user1","schools/school_A001","schools/school_A001/members/user1","schools/school_A001","schools/school_A001"]);
console.log("V47 verified school session tests passed");
