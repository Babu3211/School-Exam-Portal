import assert from "node:assert/strict";
import {planV46MarksQuery,readV46MarksForSchool} from "../src/v47/v46-marks-query-adapter.mjs";
const a=planV46MarksQuery({schoolId:"school_A001",className:"9",subject:"Computer",section:" A "});
const b=planV46MarksQuery({schoolId:"school_B001",className:"9",subject:"Computer"});
assert.equal(a.collectionPath,"schools/school_A001/marks");
assert.equal(b.collectionPath,"schools/school_B001/marks");
assert.deepEqual(a.filters,[["className","==","9"],["subject","==","Computer"],["section","==","A"]]);
assert.deepEqual(b.filters,[["className","==","9"],["subject","==","Computer"]]);
assert.equal(a.readOnlyPlan,true);
assert.equal(a.preservesV46Fields,true);
assert.throws(()=>planV46MarksQuery({schoolId:"../invalid",className:"9",subject:"Computer"}));
assert.throws(()=>planV46MarksQuery({schoolId:"school_A001",className:"",subject:"Computer"}));
assert.throws(()=>planV46MarksQuery({schoolId:"school_A001",className:"9",subject:"Computer",section:12}));
const calls=[];
const gateway={queryCollection:async(path,filters)=>{calls.push({path,filters});return [{id:"mark1",className:"9",subject:"Computer"}];}};
const rows=await readV46MarksForSchool({schoolId:"school_A001",className:"9",subject:"Computer",section:"A",gateway});
assert.equal(rows.length,1);
assert.equal(calls[0].path,"schools/school_A001/marks");
assert.deepEqual(calls[0].filters,a.filters);
await assert.rejects(readV46MarksForSchool({schoolId:"../invalid",className:"9",subject:"Computer",gateway}));
await assert.rejects(readV46MarksForSchool({schoolId:"school_A001",className:"9",subject:"Computer",gateway:{}}));
assert.equal(calls.length,1,"Rejected queries must not access the gateway");
const wrongTenant={queryCollection:async()=>[{id:"m2",schoolId:"school_B001",className:"9",subject:"Computer"}]};
await assert.rejects(readV46MarksForSchool({schoolId:"school_A001",className:"9",subject:"Computer",gateway:wrongTenant}),/tenant mismatch/);
const matchingTenant={queryCollection:async()=>[{id:"m3",schoolId:"school_A001",className:"9",subject:"Computer"}]};
assert.equal((await readV46MarksForSchool({schoolId:"school_A001",className:"9",subject:"Computer",gateway:matchingTenant})).length,1);
await assert.rejects(readV46MarksForSchool({schoolId:"school_A001",className:"9",subject:"Computer",gateway:{queryCollection:async()=>null}}),/Invalid marks query response/);
console.log("V47 tenant marks query compatibility adapter tests passed");
