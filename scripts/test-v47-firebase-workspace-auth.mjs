import assert from "node:assert/strict";
import {createV47FirebaseTokenProvider} from "../src/v47/firebase-workspace-auth.mjs";
const user={isAnonymous:false,getIdToken:async()=>"firebase-token"};
const auth={currentUser:user};
const provider=createV47FirebaseTokenProvider({auth});
assert.equal(await provider(),"firebase-token");
auth.currentUser=null;
await assert.rejects(provider(),/Login required/);
auth.currentUser={isAnonymous:true,getIdToken:async()=>"anonymous"};
await assert.rejects(provider(),/Login required/);
let resolveToken;
const pendingUser={isAnonymous:false,getIdToken:()=>new Promise(resolve=>{resolveToken=resolve;})};
auth.currentUser=pendingUser;
const pending=provider();
auth.currentUser={isAnonymous:false,getIdToken:async()=>"new-token"};
resolveToken("old-token");
await assert.rejects(pending,/Login session changed/);
assert.equal(await provider(),"new-token");
assert.throws(()=>createV47FirebaseTokenProvider({auth:{}}),/Firebase Auth instance/);
console.log("V47 Firebase workspace token provider tests passed");
