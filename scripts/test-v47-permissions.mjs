import assert from 'node:assert/strict';
import {canAccessSchool,canManageSchools} from '../v47/permissions.mjs';
const admin={uid:'admin123',active:true,role:'school_admin',schoolId:'300160001'};
const viewer={uid:'viewer123',active:true,role:'viewer',schoolId:'300160001'};
const teacher={uid:'teacher123',active:true,role:'teacher',schoolId:'300160001'};
const superAdmin={uid:'super123',active:true,role:'super_admin'};
assert.equal(canAccessSchool(admin,'300160001','write'),true);
assert.equal(canAccessSchool(admin,'300160002','read'),false);
assert.equal(canAccessSchool(viewer,'300160001','read'),true);
assert.equal(canAccessSchool(viewer,'300160001','write'),false);
assert.equal(canAccessSchool(teacher,'300160001','write'),false);
assert.equal(canAccessSchool({...teacher,assignedWrite:true},'300160001','write'),false);
assert.equal(canAccessSchool(superAdmin,'300160002','read'),true);
assert.equal(canAccessSchool(superAdmin,'300160002','write'),false);
assert.equal(canManageSchools(admin),false);
assert.equal(canManageSchools(superAdmin),true);
assert.equal(canAccessSchool({...admin,active:false},'300160001'),false);
assert.equal(canAccessSchool({...admin,uid:undefined},'300160001','read'),false);
assert.equal(canAccessSchool(admin,'school_001','read'),false);
assert.equal(canManageSchools({...superAdmin,uid:undefined}),false);
console.log('V47 role boundary tests passed');
