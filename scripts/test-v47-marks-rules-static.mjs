import assert from 'node:assert/strict';import {readFileSync} from 'node:fs';
const rules=readFileSync('v47/firestore.rules','utf8');
assert.match(rules,/function validMark\(docId\)/);
assert.match(rules,/match \/marks\/\{docId\}/);
assert.match(rules,/allow create, update: if schoolAdmin\(schoolId\) && validMark\(docId\)/);
assert.match(rules,/request\.resource\.data\.term in \['1st','2nd','final'\]/);
assert.match(rules,/students\/\$\(request\.resource\.data\.studentId\)/);
assert.match(rules,/subjects\/\$\(request\.resource\.data\.subjectId\)/);
assert.equal((rules.match(/rules_version = '2';/g)||[]).length,1,'Exactly one rules header');
assert.equal((rules.match(/match \/\{document=\*\*\}/g)||[]).length,1,'Exactly one root fallback');
assert.equal((rules.match(/match \/marks\/\{docId\}/g)||[]).length,1,'Exactly one marks match');
assert.equal((rules.match(/function validMark\(docId\)/g)||[]).length,1,'Exactly one marks validator');
assert.equal((rules.match(/match \/\{collection\}\/\{docId\}/g)||[]).length,1,'Exactly one generic matcher');
assert.equal((rules.match(/\{/g)||[]).length,(rules.match(/\}/g)||[]).length,'Balanced braces');
assert.doesNotMatch(rules,/No legacy root collection access[\s\S]*?function validMark/,'No trailing duplicated rule fragments');
const generic=rules.slice(rules.indexOf('match /{collection}/{docId}'));
assert.doesNotMatch(generic,/['"]marks['"]/,'Generic wildcard must not bypass mark validation');
console.log('V47 mark rules static tests passed');
