import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const rules=readFileSync('v47/firestore.rules','utf8');
assert.match(rules,/function validRawMark\(sid, id\)/);
assert.match(rules,/match \/marks\/\{id\}/);
assert.match(rules,/match \/marks\/\{id\} \{[\s\S]*?allow create, update, delete: if false;/);
assert.match(rules,/match \/marks\/\{id\} \{[\s\S]*?allow create, update, delete: if false;/);
assert.match(rules,/match \/marks\/\{id\} \{[\s\S]*?allow create, update, delete: if false;/);
assert.match(rules,/match \/marks\/\{id\} \{[\s\S]*?allow delete: if false;/);
assert.match(rules,/data\.term in \['weekly','monthly','1st','2nd','3rd','final'\]/);
assert.match(rules,/function teacherMarkAllowed\(sid, id\)/);
assert.match(rules,/function scopedRecord\(sid\)/);
assert.equal((rules.match(/rules_version = '2';/g)||[]).length,1);
assert.equal((rules.match(/match \/\{document=\*\*\}/g)||[]).length,1);
assert.equal((rules.match(/match \/marks\/\{id\}/g)||[]).length,1);
assert.equal((rules.match(/function validRawMark\(sid, id\)/g)||[]).length,1);
assert.equal((rules.match(/match \/\{collection\}\/\{id\}/g)||[]).length,1);
const generic=rules.slice(rules.indexOf('match /{collection}/{id}'));
assert.doesNotMatch(generic,/['\"]marks['\"]/, 'Generic wildcard must not bypass mark validation');
console.log('V47 marks rules static tests passed');
