import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {createSchoolDraft,schoolCollectionPath} from "../src/v47/tenant-domain.mjs";
const manifest=JSON.parse(readFileSync(new URL("../manifest.webmanifest",import.meta.url),"utf8"));
const sw=readFileSync(new URL("../sw.js",import.meta.url),"utf8");
const release=readFileSync(new URL("../.github/workflows/v46-production-release.yml",import.meta.url),"utf8");
assert.equal(manifest.name,"SMSS Exam Portal");
assert.equal(manifest.display,"standalone");
assert.equal(manifest.start_url,"./");
assert.equal(manifest.scope,"./");
assert.ok(manifest.icons.some(icon=>icon.sizes==="192x192"));
assert.ok(manifest.icons.some(icon=>icon.sizes==="512x512"));
assert.match(sw,/request\.mode === 'navigate'/);
assert.match(sw,/CACHE_NAME/);
assert.match(release,/github\.ref == 'refs\/heads\/main'/);
assert.match(release,/DEPLOY-V46/);
assert.match(release,/BACKUP-VERIFIED/);
assert.match(release,/ROLES-VERIFIED/);
const a=createSchoolDraft({schoolId:"tenant_0001",name:"Pilot A",iemisCode:"A1"});
const b=createSchoolDraft({schoolId:"tenant_0002",name:"Pilot B",iemisCode:"B2"});
assert.notEqual(schoolCollectionPath(a.schoolId,"marks"),schoolCollectionPath(b.schoolId,"marks"));
console.log("V47 APK/PWA and V46 release compatibility static checks passed");
