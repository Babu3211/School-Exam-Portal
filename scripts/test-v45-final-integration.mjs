import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const html=readFileSync('index.html','utf8');
const rules=readFileSync('firestore.rules','utf8');
const activity=readFileSync('user-activity.js','utf8');
const idle=readFileSync('idle-logout.js','utf8');
for(const label of ['Home','School Profile','Student Record','Manage Exam','Teacher | Staff','Reports','Settings'])assert.ok(html.includes(label),'Approved dashboard menu missing: '+label);
assert.ok(!html.includes('V45 Trial'),'Obsolete dashboard label must not return');
assert.ok(html.includes('import {initUserActivity} from "./user-activity.js'),'Activity module must be loaded');
assert.ok(html.includes('import {initIdleLogout} from "./idle-logout.js'),'Idle module must be loaded');
assert.ok(html.includes('minutes:60'),'60-minute timeout required');
assert.ok(html.includes('onTimeout:async user=>{await signOutWithActivity(user);}'),'Idle signout must occur even when activity logging fails');
assert.ok(html.includes('await signOutWithActivity(user);'),'Manual logout must not be blocked by activity logging');
assert.ok(html.includes('idleSession.start(user)')&&html.includes('idleSession.stop()'),'Idle lifecycle incomplete');
assert.ok(html.includes('await userActivity.login(credential.user)'),'Login event missing');
assert.ok(html.includes('if(user)await Promise.race([userActivity.logout(user),new Promise(resolve=>setTimeout(resolve,1500))])'),'Logout event must have a bounded audit write');
assert.ok(html.includes('finally{await signOut(auth);}'),'Firebase sign-out must proceed after audit timeout');
assert.ok(html.includes('window.renderSmssUserActivity()'),'Admin dashboard render missing');
assert.ok(html.includes('if(!isAdmin())return;const panel=document.getElementById("smssUserActivity")'),'Activity panel must be admin-only');
for(const collection of ['user_activity','user_presence'])assert.ok(rules.includes('match /'+collection+'/'),'Firestore permissions missing for '+collection);
assert.ok(rules.includes('allow get, list: if isAdmin();'),'Only admins may read activity records');
assert.ok(rules.includes('request.resource.data.uid == request.auth.uid'),'User cannot spoof another user');
assert.ok(activity.includes('activeWithin(x.updatedAt,120000)'),'Presence freshness required');
assert.ok(idle.includes('if(now()-Math.max(lastActivity,read())>=idleMs)'),'Expired session must not be extended');
console.log('V45 approved dashboard and user activity integration checks passed');
