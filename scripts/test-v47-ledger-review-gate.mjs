import assert from 'node:assert/strict';
import {buildRawLedgerPreview} from '../v47/raw-ledger-preview.mjs';
import {assertLedgerReviewExportable} from '../v47/ledger-review-gate.mjs';
import {ledgerExceptionsCsv} from '../v47/ledger-exceptions-export.mjs';
const base={schoolClass:'9',term:'final',students:[{id:'s1',name:'Student',class:'9'}],subjects:[{id:'math',name:'Mathematics',class:'9',active:true}],assignments:[{studentId:'s1',subjectId:'math',class:'9'}],rawMarks:[],componentMarks:[],allPagesLoaded:true};
const missing=buildRawLedgerPreview(base);
assert.equal(assertLedgerReviewExportable(missing),true);
assert.match(ledgerExceptionsCsv(missing),/missing_mark/);
assert.throws(()=>assertLedgerReviewExportable(buildRawLedgerPreview({...base,allPagesLoaded:false})),/incomplete/);
assert.throws(()=>assertLedgerReviewExportable(buildRawLedgerPreview({...base,students:[]})),/roster|integrity/);
assert.throws(()=>assertLedgerReviewExportable(buildRawLedgerPreview({...base,assignments:[]})),/roster|integrity/);
assert.throws(()=>assertLedgerReviewExportable(buildRawLedgerPreview({...base,assignments:[...base.assignments,...base.assignments]})),/integrity/);
assert.throws(()=>assertLedgerReviewExportable(buildRawLedgerPreview({...base,rawMarks:[{studentId:'other',subjectId:'math',class:'9',term:'final',theory:10,practical:10}]})),/integrity/);
const invalid=buildRawLedgerPreview({...base,rawMarks:[{studentId:'s1',subjectId:'math',class:'9',term:'final',theory:-1,practical:0}]});
assert.equal(assertLedgerReviewExportable(invalid),true);
assert.match(ledgerExceptionsCsv(invalid),/invalid_score_or_format/);
assert.throws(()=>assertLedgerReviewExportable({...missing,issues:['unrecognized_integrity_issue']}),/integrity/);
assert.throws(()=>assertLedgerReviewExportable({...missing,publishable:true}),/Official/);
console.log('V47 shared diagnostic export integrity gate tests passed');
