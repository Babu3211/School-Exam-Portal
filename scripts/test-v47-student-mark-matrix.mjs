import assert from 'node:assert/strict';
import {buildStudentMarkMatrix} from '../v47/student-mark-matrix.mjs';
const students=[{id:'s1',name:'Student One',class:'9'},{id:'s2',name:'Student Two',class:'9'}];
const subjects=[{id:'computer',name:'Computer',class:'9',active:true},{id:'math',name:'Mathematics',class:'9',active:true}];
const assignments=students.flatMap(s=>subjects.map(x=>({studentId:s.id,subjectId:x.id,class:'9'})));
const component={studentId:'s1',subjectId:'computer',class:'9',term:'final',scores:{component_a:4,component_b:36,component_c:10}};
const math={studentId:'s1',subjectId:'math',class:'9',term:'final',theory:30,practical:8};
const args={schoolClass:'9',term:'final',students,subjects,assignments,rawMarks:[math],componentMarks:[component],allPagesLoaded:true};
const partial=buildStudentMarkMatrix(args);
assert.equal(partial.students.length,2);
assert.equal(partial.students[0].recordedSubjects,2);
assert.equal(partial.students[1].recordedSubjects,0);
assert.equal(partial.students[1].subjects.filter(x=>x.status==='missing').length,2);
assert.equal(partial.complete,false);
assert.equal(partial.publishable,false);
assert.equal(partial.officialLedger,false);
const full=buildStudentMarkMatrix({...args,rawMarks:[math,{...math,studentId:'s2'}],componentMarks:[component,{...component,studentId:'s2'}]});
assert.equal(full.complete,true);
assert.equal(full.students[1].recordedSubjects,2);
assert.equal(full.gradeCalculated,false);
const duplicate=buildStudentMarkMatrix({...args,rawMarks:[math,math]});
assert.equal(duplicate.students[0].subjects.find(x=>x.subjectId==='math').status,'duplicate');
assert.equal(duplicate.complete,false);
const wrong=buildStudentMarkMatrix({...args,rawMarks:[math,{studentId:'s2',subjectId:'computer',class:'9',term:'final',theory:10,practical:10}]});
assert.equal(wrong.students[1].subjects.find(x=>x.subjectId==='computer').status,'wrong_format');
assert.equal(wrong.complete,false);
const unloaded=buildStudentMarkMatrix({...args,allPagesLoaded:false});
assert.ok(unloaded.issues.includes('pagination_incomplete'));
assert.equal(unloaded.complete,false);
console.log('V47 student mark matrix diagnostic tests passed');
