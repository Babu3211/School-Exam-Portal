import assert from "node:assert/strict";
import {mayWriteExamRecord as allowed} from "../src/v47/exam-write-policy.mjs";
const membership={uid:"teacherA",schoolId:"school_A001",active:true,roles:["subject_teacher"]};
const assignment={uid:"teacherA",schoolId:"school_A001",active:true,kind:"subject_teacher",classId:"9",subjectId:"computer",terms:["first","second","final"]};
const input={membership,assignment,schoolId:"school_A001",classId:"9",subjectId:"computer",term:"first",resource:"marks"};
assert.equal(allowed(input),true);
assert.equal(allowed({...input,schoolId:"school_B001"}),false);
assert.equal(allowed({...input,classId:"10"}),false);
assert.equal(allowed({...input,subjectId:"math"}),false);
assert.equal(allowed({...input,term:"midterm"}),false);
assert.equal(allowed({...input,membership:{...membership,roles:["viewer","subject_teacher"]}}),false);
assert.equal(allowed({...input,assignment:{...assignment,active:false}}),false);
assert.equal(allowed({...input,resource:"attendance"}),false);
const classTeacher={...membership,roles:["class_teacher"]};
const classAssignment={...assignment,kind:"class_teacher",subjectIds:["computer","math"]};
assert.equal(allowed({...input,membership:classTeacher,assignment:classAssignment,resource:"attendance"}),true);
assert.equal(allowed({...input,membership:classTeacher,assignment:classAssignment,subjectId:"math"}),true);
assert.equal(allowed({...input,membership:classTeacher,assignment:classAssignment,subjectId:"science"}),false);
assert.equal(allowed({...input,membership:{...membership,roles:["school_admin"]},assignment:null}),true);
assert.equal(allowed({...input,classId:"13"}),false);
assert.equal(allowed({...input,classId:"ECD",assignment:{...assignment,classId:"ECD"}}),true);
console.log("V47 exam write policy checks passed");
