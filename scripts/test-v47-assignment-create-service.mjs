import assert from 'node:assert/strict';
import {createSubjectAssignment} from '../v47/assignment-create-service.mjs';
import {subjectAssignmentId} from '../v47/assignment-validation.mjs';
const docs=new Map([['schools/school_001/students/s1',{class:'6'}],['schools/school_001/subjects/math_6',{class:'6',active:true}]]);
const api={doc:(_db,...p)=>p.join('/'),runTransaction:async(_db,callback)=>{const writes=[];await callback({get:async ref=>({exists:()=>docs.has(ref),data:()=>docs.get(ref)}),set:(ref,value)=>writes.push([ref,value])});for(const [ref,value]of writes)docs.set(ref,value)}};
const actor={role:'school_admin',active:true,schoolId:'school_001'},input={studentId:'s1',subjectId:'math_6',class:'6'},args={db:{},api,actor,schoolId:'school_001',input};
assert.equal(subjectAssignmentId(input),'s1:math_6');
assert.notEqual(subjectAssignmentId({studentId:'a_b',subjectId:'c',class:'6'}),subjectAssignmentId({studentId:'a',subjectId:'b_c',class:'6'}));
assert.equal((await createSubjectAssignment(args)).id,'s1:math_6');assert.equal(docs.size,3);
await assert.rejects(()=>createSubjectAssignment(args),/already exists/);
await assert.rejects(()=>createSubjectAssignment({...args,actor:{...actor,role:'viewer'}}));
await assert.rejects(()=>createSubjectAssignment({...args,schoolId:'school_002'}));
docs.get('schools/school_001/subjects/math_6').active=false;
await assert.rejects(()=>createSubjectAssignment({...args,input:{...input,subjectId:'math_6'}}),/inactive/);
assert.throws(()=>subjectAssignmentId({...input,studentId:'bad\/id'}));
console.log('V47 subject assignment create-only tests passed');
