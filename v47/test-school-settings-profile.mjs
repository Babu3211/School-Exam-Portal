import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {validateSchoolProfile,schoolProfileView,profileSignature,canEditSchoolProfile} from './school-settings-profile.mjs';
const id='300160003';
const valid={schoolId:id,nameEnglish:'SMSS School',nameNepali:'विद्यालय',addressEnglish:'Kathmandu',addressNepali:'काठमाडौं'};
assert.deepEqual(validateSchoolProfile(valid,id),valid);
assert.throws(()=>validateSchoolProfile({...valid,schoolId:'999999999'},id),/School ID cannot/);
assert.throws(()=>validateSchoolProfile({...valid,nameEnglish:'a'},id),/length is invalid/);
assert.throws(()=>validateSchoolProfile({...valid,addressEnglish:'x'.repeat(301)},id),/length is invalid/);
assert.throws(()=>validateSchoolProfile({...valid,nameNepali:'bad\u0001'},id),/unsupported/);
assert.throws(()=>validateSchoolProfile({...valid,nameNepali:42},id),/must be text/);
assert.equal(canEditSchoolProfile('school_admin'),true);
for(const role of ['viewer','teacher','super_admin','admin',null])assert.equal(canEditSchoolProfile(role),false);
assert.equal(schoolProfileView({},'Registered School').nameEnglish,'Registered School');
assert.equal(schoolProfileView({nameEnglish:'Updated'},'Original').nameEnglish,'Updated');
assert.notEqual(profileSignature(valid),profileSignature({...valid,addressNepali:'Changed'}));
const js=readFileSync(new URL('./school-settings-console.mjs',import.meta.url),'utf8');
const html=readFileSync(new URL('./school-settings.html',import.meta.url),'utf8');
assert.match(html,/id="saveProfile" disabled hidden/);
assert.match(html,/id="nameEnglish"/);
assert.match(html,/id="nameNepali"/);
assert.match(html,/id="addressEnglish"/);
assert.match(html,/id="addressNepali"/);
assert.match(js,/verifySchoolSession\(/);
assert.match(js,/if\(currentSession\.role!=='school_admin'/);
assert.match(js,/api\.runTransaction\(db/);
assert.match(js,/transaction\.get\(memberRef/);
assert.match(js,/transaction\.get\(profileRef/);
assert.match(js,/member\?\.role!=='school_admin'/);
assert.match(js,/settings\.schoolId!==current\.schoolId/);
assert.match(js,/profileSignature\(schoolProfileView/);
assert.match(js,/actor!==current/);
assert.doesNotMatch(js,/api\.updateDoc\(registryRef/);
console.log('PASS V47 school-scoped bilingual settings, admin-only transaction, viewer/teacher read-only and IEMIS ID preserved');
