import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
const script=new URL('./audit-v46-feature-parity.mjs',import.meta.url);
const jsonRun=spawnSync(process.execPath,[script.pathname,'--json'],{encoding:'utf8'});
assert.equal(jsonRun.status,0,jsonRun.stderr);
const report=JSON.parse(jsonRun.stdout);
assert.equal(report.kind,'v46-to-v47-source-inventory');
assert.equal(report.functionalParityVerified,false);
assert.ok(report.features.length>=14);
assert.ok(report.features.every(f=>f.parityVerified===false));
assert.equal(report.features.find(f=>f.feature==='Dashboard').v47Routes[0].linked,true);
assert.equal(report.features.find(f=>f.feature==='Dashboard').prototypeWarning,true);
assert.ok(report.features.some(f=>f.feature==='Marks entry'));
const staff=report.features.find(f=>f.feature==='Teacher and staff records');
assert.equal(staff.v47Routes[0].path,'v47/staff.html');
assert.equal(staff.sourcePresent,true,'Staff route must be registered but not counted as functional parity');
const primary=report.features.find(f=>f.feature==='Primary Assessment 1–5');
assert.ok(primary,'Primary assessment must be an explicit parity requirement');
assert.equal(primary.sourcePresent,true);
assert.equal(primary.prototypeWarning,true,'Reference-only assessment does not satisfy operational parity');
assert.equal(primary.parityVerified,false);
const question=report.features.find(f=>f.feature==='Question paper');
assert.equal(question.sourcePresent,true,'V46 Question Paper source must have a V47 read-only route');
assert.equal(question.prototypeWarning,true,'Practice-paper preview is NOT V46 feature parity');
assert.equal(question.parityVerified,false,'Teacher-approved paper generation not yet migrated');
const readable=spawnSync(process.execPath,[script.pathname],{encoding:'utf8'});
assert.equal(readable.status,0,readable.stderr);
assert.match(readable.stdout,/Functional parity verified: NO/);
const gate=spawnSync(process.execPath,[script.pathname,'--require-parity'],{encoding:'utf8'});
assert.notEqual(gate.status,0,'Source-only evidence must not unlock production');
assert.match(gate.stderr,/independent verification required/);
console.log('V47 source inventory reports gaps without falsely approving release');
