const html=readFileSync(new URL('./marks-entry.html',import.meta.url),'utf8');
assert.match(html,/id="downloadClassReview" disabled/);
assert.match(html,/id="reviewFile" type="file"/);
assert.match(html,/id="verifyClassReview" disabled/);
assert.match(ui,/reviewPackage=buildClassMarksReviewPackage/);
assert.match(ui,/reviewPackage=null;\$\('downloadClassReview'\)\.disabled=true/);
assert.match(ui,/\$\('downloadClassReview'\)\.onclick=/);
assert.match(ui,/URL\.revokeObjectURL/);
assert.match(ui,/verifyClassMarksReviewPackage\(\{json,actor/);
assert.match(ui,/const roster=await loadCompleteClassRoster/);
assert.match(ui,/const finalSession=await verifySchoolSession/);
assert.match(ui,/reviewVerifyResult/);
const draftListener=ui.slice(ui.indexOf("$('classMarkRows').addEventListener('input'"),ui.indexOf('function collectClassMarkEntries()'));
assert.match(draftListener,/reviewPackage=null/);
assert.match(draftListener,/\$\('reviewFile'\)\.value=''/);
