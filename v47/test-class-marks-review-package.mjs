import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {buildClassMarksReviewPackage} from './class-marks-review-package.mjs';
const settings={schoolId:'12345',classId:'9',subjectId:'math',examId:'final',active:true,components:[{key:'theory',name:'Theory',fullMarks:75},{key:'practical',name:'Practical',fullMarks:25}]};
const actor={uid:'admin',role:'school_admin',active:true,schoolId:'12345'};
const base={actor,schoolId:'12345',classId:'9',subjectId:'math',examId:'final',settings};
const ids=Array.from({length:205},(_,i)=>'s'+String(i+1).padStart(4,'0'));
const drafts=ids.map(studentId=>({studentId,values:{theory:65,practical:20}}));
const a=buildClassMarksReviewPackage({...base,expectedStudentIds:ids,drafts});
const b=buildClassMarksReviewPackage({...base,expectedStudentIds:[...ids].reverse(),drafts:[...drafts].reverse()});
assert.equal(a.json,b.json);
assert.equal(a.rosterCount,205);
const data=JSON.parse(a.json);
assert.equal(data.entries.length,205);
assert.equal(data.entries[0].studentId,'s0001');
assert.equal(data.entries.at(-1).studentId,'s0205');
assert.equal(data.writeAuthorized,false);
assert.equal(data.publicationAllowed,false);
assert.throws(()=>buildClassMarksReviewPackage({...base,expectedStudentIds:ids,drafts:drafts.slice(1)}),/complete/);
assert.throws(()=>buildClassMarksReviewPackage({...base,actor:{...actor,role:'viewer'},expectedStudentIds:ids,drafts}),/admin/);
const absent=buildClassMarksReviewPackage({...base,expectedStudentIds:['s1'],drafts:[{studentId:'s1',isAbsent:true}]});
assert.equal(JSON.parse(absent.json).entries[0].values,null);
