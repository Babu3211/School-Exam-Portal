import assert from 'node:assert/strict';
import {normalizeSchool,schoolRegistryPath} from './school-registry.mjs';
import {normalizeMembership,canReadSchool,canManageSchool,canWriteSchool} from './school-membership.mjs';
import {selectableSchools,chooseSchool} from './school-selector.mjs';
import {boundedPageSize,stablePage} from './school-pagination.mjs';
import {assignmentKey,isAssigned} from './school-assignments.mjs';
import {auditEvent} from './school-audit.mjs';
import {tenantExportManifest} from './school-export.mjs';
import {prepareSchoolRegistration} from './school-registration.mjs';
import {authorizeSchoolAction} from './school-role-guards.mjs';
assert.equal(normalizeSchool({id:'12345678',iemisCode:'12345678',name:' School A '}).name,'School A');
assert.throws(()=>normalizeSchool({id:'../87654321',name:'Bad school'}),Error);
assert.equal(schoolRegistryPath('12345678'),'schools/12345678');
const admin=normalizeMembership('12345678','user_0001','school_admin');
assert.equal(admin.path,'schools/12345678/members/user_0001');
assert.equal(canManageSchool(admin),true);
assert.equal(canWriteSchool({role:'teacher',active:true}),false);
assert.equal(canWriteSchool(admin),true);
assert.equal(canReadSchool({role:'viewer',active:true}),true);
assert.equal(canManageSchool({role:'viewer',active:true}),false);
assert.throws(()=>normalizeMembership('12345678','user_0001','super_admin'),Error);
assert.deepEqual(selectableSchools([{schoolId:'12345678',role:'school_admin',active:true},{schoolId:'12345678',role:'viewer',active:true},{schoolId:'87654321',role:'teacher',active:false}]),[]);
assert.deepEqual(selectableSchools([{schoolId:'12345678',role:'school_admin',active:true},{schoolId:'12345678',role:'school_admin',active:true}]),[{id:'12345678',role:'school_admin'}]);
assert.throws(()=>chooseSchool([{schoolId:'12345678',role:'school_admin',active:true},{schoolId:'12345678',role:'viewer',active:true}],'12345678'));
assert.throws(()=>chooseSchool([{schoolId:'12345678',role:'school_admin',active:true}],'87654321'));
assert.equal(boundedPageSize(999),100);
assert.equal(stablePage([{id:'b'},{id:'a'},{id:'c'}],{limit:2}).nextCursor,'b');
const key=assignmentKey('12345678','Class 10','Science');
assert.equal(isAssigned([key],'12345678','Class 10','Science','A'),true);
assert.equal(isAssigned([key],'87654321','Class 10','Science','A'),false);
assert.equal(authorizeSchoolAction({membership:{active:true,role:'teacher',schoolId:'12345678'},action:'write',schoolId:'12345678',className:'Class 10',subject:'Science',section:'A',assignments:[key]}),false);
assert.equal(authorizeSchoolAction({membership:{active:true,role:'viewer',schoolId:'12345678'},action:'write',schoolId:'12345678',className:'Class 10',subject:'Science',assignments:[key]}),false);
assert.equal(auditEvent({schoolId:'12345678',actorUid:'user_0001',action:'delete',entity:'students',entityId:'student_1'}).action,'delete');
assert.throws(()=>tenantExportManifest('12345678',['schools/87654321/marks']),TypeError);
assert.equal(prepareSchoolRegistration({id:'12345678',iemisCode:'12345678',name:'School A'},'user_0001').requiresSuperAdmin,true);
assert.equal(prepareSchoolRegistration({id:'12345678',iemisCode:'12345678',name:'School A'},'user_0001').adminMembership.active,false);
assert.equal(normalizeSchool({id:'12345678',iemisCode:'12345678',name:'School A',address:'Kathmandu'}).address,undefined);
assert.deepEqual(Object.keys(normalizeSchool({id:'12345678',iemisCode:'12345678',name:'School A'})).sort(),['active','id','iemisCode','name']);
assert.throws(()=>tenantExportManifest('12345678',['schools/12345678/marks/x/other/y']),TypeError);
assert.throws(()=>tenantExportManifest('12345678',['schools/12345678/students/student_1']),TypeError);
assert.throws(()=>tenantExportManifest('12345678',['schools/12345678/members']),TypeError);
assert.equal(authorizeSchoolAction({membership:{active:true,role:'school_admin',schoolId:'12345678'},action:'read',schoolId:'87654321'}),false);
assert.deepEqual(selectableSchools([{schoolId:'12345678',role:'invalid',active:true}]),[]);
assert.throws(()=>stablePage([{id:'a'}],{afterId:4}),TypeError);
console.log('V47 foundational module tests passed');
