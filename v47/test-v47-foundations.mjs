import assert from 'node:assert/strict';
import {normalizeSchool,schoolRegistryPath} from './school-registry.mjs';
import {normalizeMembership,canReadSchool,canManageSchool,canWriteSchool} from './school-membership.mjs';
import {selectableSchools,chooseSchool} from './school-selector.mjs';
import {boundedPageSize,stablePage} from './school-pagination.mjs';
import {assignmentKey,isAssigned} from './school-assignments.mjs';
import {auditEvent} from './school-audit.mjs';
import {tenantExportManifest} from './school-export.mjs';
import {prepareSchoolRegistration} from './school-registration.mjs';
import {authorizeSchoolAction} from './school-role-guards.mjs';
assert.equal(normalizeSchool({id:'school_A',name:' School A '}).name,'School A');
assert.throws(()=>normalizeSchool({id:'../school_B',name:'Bad school'}),Error);
assert.equal(schoolRegistryPath('school_A'),'schools/school_A');
const admin=normalizeMembership('school_A','user_0001','school_admin');
assert.equal(admin.path,'schools/school_A/members/user_0001');
assert.equal(canManageSchool(admin),true);
assert.equal(canWriteSchool({role:'teacher',active:true}),false);
assert.equal(canWriteSchool(admin),true);
assert.equal(canReadSchool({role:'viewer',active:true}),true);
assert.equal(canManageSchool({role:'viewer',active:true}),false);
assert.throws(()=>normalizeMembership('school_A','user_0001','super_admin'),Error);
assert.deepEqual(selectableSchools([{schoolId:'school_A',role:'school_admin',active:true},{schoolId:'school_A',role:'viewer',active:true},{schoolId:'school_B',role:'teacher',active:false}]),[]);
assert.deepEqual(selectableSchools([{schoolId:'school_A',role:'school_admin',active:true},{schoolId:'school_A',role:'school_admin',active:true}]),[{id:'school_A',role:'school_admin'}]);
assert.throws(()=>chooseSchool([{schoolId:'school_A',role:'school_admin',active:true},{schoolId:'school_A',role:'viewer',active:true}],'school_A'));
assert.throws(()=>chooseSchool([{schoolId:'school_A',role:'school_admin',active:true}],'school_B'));
assert.equal(boundedPageSize(999),100);
assert.equal(stablePage([{id:'b'},{id:'a'},{id:'c'}],{limit:2}).nextCursor,'b');
const key=assignmentKey('school_A','Class 10','Science');
assert.equal(isAssigned([key],'school_A','Class 10','Science','A'),true);
assert.equal(isAssigned([key],'school_B','Class 10','Science','A'),false);
assert.equal(authorizeSchoolAction({membership:{active:true,role:'teacher',schoolId:'school_A'},action:'write',schoolId:'school_A',className:'Class 10',subject:'Science',section:'A',assignments:[key]}),false);
assert.equal(authorizeSchoolAction({membership:{active:true,role:'viewer',schoolId:'school_A'},action:'write',schoolId:'school_A',className:'Class 10',subject:'Science',assignments:[key]}),false);
assert.equal(auditEvent({schoolId:'school_A',actorUid:'user_0001',action:'delete',entity:'students',entityId:'student_1'}).action,'delete');
assert.throws(()=>tenantExportManifest('school_A',['schools/school_B/marks']),TypeError);
assert.equal(prepareSchoolRegistration({id:'school_A',name:'School A'},'user_0001').requiresSuperAdmin,true);
assert.equal(prepareSchoolRegistration({id:'school_A',name:'School A'},'user_0001').adminMembership.active,false);
assert.equal(normalizeSchool({id:'school_A',name:'School A',address:'Kathmandu'}).address,undefined);
assert.deepEqual(Object.keys(normalizeSchool({id:'school_A',name:'School A'})).sort(),['active','id','iemisCode','name']);
assert.throws(()=>tenantExportManifest('school_A',['schools/school_A/marks/x/other/y']),TypeError);
assert.throws(()=>tenantExportManifest('school_A',['schools/school_A/students/student_1']),TypeError);
assert.throws(()=>tenantExportManifest('school_A',['schools/school_A/members']),TypeError);
assert.equal(authorizeSchoolAction({membership:{active:true,role:'school_admin',schoolId:'school_A'},action:'read',schoolId:'school_B'}),false);
assert.deepEqual(selectableSchools([{schoolId:'school_A',role:'invalid',active:true}]),[]);
assert.throws(()=>stablePage([{id:'a'}],{afterId:4}),TypeError);
console.log('V47 foundational module tests passed');
