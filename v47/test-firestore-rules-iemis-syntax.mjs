import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const rules=readFileSync(new URL('./firestore.rules',import.meta.url),'utf8');
const start=rules.indexOf('function validSchool(sid) {');
const end=rules.indexOf('match /v47_super_admins/',start);
assert.ok(start>=0&&end>start,'School validation block must exist');
const school=rules.slice(start,end);
assert.equal((school.match(/sid\.matches\(/g)||[]).length,1);
assert.ok(school.includes("sid.matches('^[0-9]{5,20}$')"),'Closed IEMIS regex required');
assert.ok(school.includes("request.resource.data.keys().hasOnly(['id', 'name', 'iemisCode', 'active'])"));
assert.ok(school.includes("request.resource.data.keys().hasAll(['id', 'name', 'iemisCode', 'active'])"));
assert.ok(school.includes("request.resource.data.iemisCode == sid"));
assert.ok(school.includes("request.resource.data.active == false"));
assert.ok(!school.includes("sid.matches('^[0-9]{5,20}("),'Corrupt school pattern');
assert.equal((school.match(/'/g)||[]).length%2,0,'Unbalanced single quotes in school rule');
console.log('PASS: V47 school registration rules structural regression');
