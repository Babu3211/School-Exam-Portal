import assert from 'node:assert/strict';
import {requireTenantRecord,filterTenantRecords} from './tenant-school-filter.mjs';
import {assertStudentClass} from './student-class-guard.mjs';
import {assertImmutableTenantIdentity} from './tenant-record-identity.mjs';
import {validateAttendanceRecord} from './attendance-contract.mjs';
import {validateCompleteMarks} from './marks-completeness.mjs';
import {V47_CLASS_ORDER,sortClasses} from './school-class-order.mjs';
import {prepareDelete} from './tenant-delete-guard.mjs';
import {assertBoundedBatch} from './tenant-data-limits.mjs';
const s={schoolId:'school_A',studentId:'student_1',className:'Class 9',section:'A'};
assert.equal(requireTenantRecord('school_A',s),s);
assert.throws(()=>requireTenantRecord('school_B',s));
assert.deepEqual(filterTenantRecords('school_A',[s,{...s,schoolId:'school_B'}]),[s]);
assert.equal(assertStudentClass('school_A',s,'Class 9','A'),s);
assert.throws(()=>assertStudentClass('school_A',s,'Class 10'));
assert.equal(assertImmutableTenantIdentity(s,{...s,className:'Class 10'}),true);
assert.throws(()=>assertImmutableTenantIdentity(s,{...s,schoolId:'school_B'}));
assert.equal(validateAttendanceRecord({schoolId:'school_A',studentId:'student_1',date:'2026-11-18',status:'present'}).status,'present');
assert.throws(()=>validateAttendanceRecord({schoolId:'school_A',studentId:'student_1',date:'2026-02-30',status:'present'}));
assert.deepEqual(validateCompleteMarks('school_A',['a','b'],{a:0,b:20}),{complete:true,missing:[]});
assert.deepEqual(validateCompleteMarks('school_A',['a','b'],{a:0}),{complete:false,missing:['b']});
assert.deepEqual(validateCompleteMarks('school_A',['a'],{a:NaN}),{complete:false,missing:['a']});
assert.deepEqual(validateCompleteMarks('school_A',['a'],{a:'55'}),{complete:false,missing:['a']});
assert.deepEqual(validateCompleteMarks('school_A',['a'],{a:101}),{complete:false,missing:['a']});
assert.equal(prepareDelete({schoolId:'school_A',collection:'students',id:'student_1',firstConfirmation:true,secondConfirmation:true}).authorized,false);
assert.equal(V47_CLASS_ORDER.length,15);
assert.deepEqual(sortClasses(['Class 12','ECD','Class 1']),['ECD','Class 1','Class 12']);
assert.throws(()=>prepareDelete({schoolId:'school_A',collection:'students',id:'student_1',firstConfirmation:true,secondConfirmation:false}));
assert.equal(prepareDelete({schoolId:'school_A',collection:'students',id:'student_1',firstConfirmation:true,secondConfirmation:true}).requiresServerAuthorization,true);
assert.equal(prepareDelete({schoolId:'school_A',collection:'teachers',id:'teacher_1',firstConfirmation:true,secondConfirmation:true}).authorized,false);
assert.throws(()=>prepareDelete({schoolId:'school_A',collection:'marks',id:'mark_1',firstConfirmation:true,secondConfirmation:true}));
assert.equal(assertBoundedBatch(100),100);
assert.throws(()=>assertBoundedBatch(501));
console.log('V47 tenant invariants passed');
