import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {findSchoolMember} from './member-lookup-service.mjs';
const schoolId='12345',uid='teacher_123',actor={uid:'admin_123',active:true,role:'school_admin',schoolId};
const api={doc:(db,...parts)=>parts,getDoc:async parts=>({exists:()=>true,data:()=>({uid,schoolId,role:'teacher',active:true})})};
const input={db:{},api,actor,schoolId,uid};
assert.deepEqual(await findSchoolMember(input),{uid,role:'teacher',active:true});
assert.equal((await findSchoolMember(input)).active,true);
assert.equal(await findSchoolMember({...input,api:{...api,getDoc:async()=>({exists:()=>false})}}),null);
await assert.rejects(()=>findSchoolMember({...input,actor:{...actor,role:'viewer'}}),/School Admin/);
await assert.rejects(()=>findSchoolMember({...input,schoolId:'67890'}),/School Admin/);
await assert.rejects(()=>findSchoolMember({...input,uid:'../other'}),/Invalid member UID/);
await assert.rejects(()=>findSchoolMember({...input,api:{...api,getDoc:async()=>({exists:()=>true,data:()=>({uid,schoolId:'67890',role:'teacher',active:true})})}}),/cross-school/);
