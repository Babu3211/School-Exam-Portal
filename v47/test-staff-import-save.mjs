import assert from 'node:assert/strict';
import {importNewStaff} from './staff-import-save.mjs';
import {V46_STAFF_EXCEL_HEADERS,v46StaffExcelRow} from './v46-staff-excel-schema.mjs';
const schoolId='12345',uid='admin1',actor={schoolId,uid,role:'school_admin',active:true},base='schools/'+schoolId;
const docs=new Map([[base,{id:schoolId,active:true}],[base+'/members/'+uid,actor]]);
const row=['0007','शिक्षक','Teacher A','Address','Secondary','2081-01-01','Permanent','MA','Science','001234','कार्यरत'];
const cells=[V46_STAFF_EXCEL_HEADERS,row];
const store={schoolId,listPage:async()=>({records:[...docs].filter(([p])=>p.startsWith(base+'/staff/')).map(([p,v])=>({...v,id:p.split('/').at(-1)})).sort((a,b)=>a.id.localeCompare(b.id)),hasMore:false,cursor:null})};
const api={doc:(_db,...p)=>p.join('/'),runTransaction:async(_db,fn)=>{const writes=[];const result=await fn({get:async p=>({exists:()=>docs.has(p),data:()=>docs.get(p)}),set:(p,v)=>writes.push([p,v])});for(const [p,v]of writes)docs.set(p,v);return result;}};
const args={db:{},api,actor,schoolId,cells,store,confirmed:true,assertCurrent:()=>{}};
await assert.rejects(importNewStaff({...args,actor:{...actor,role:'viewer'}}),/Admin/);
await assert.rejects(importNewStaff({...args,confirmed:false}),/confirmation/);
await assert.rejects(importNewStaff({...args,cells:[V46_STAFF_EXCEL_HEADERS,['',...row.slice(1)]]}),/Employee ID/);
assert.equal((await importNewStaff(args)).count,1);
const staff=[...docs].filter(([p])=>p.startsWith(base+'/staff/'));
assert.equal(staff.length,1);assert.deepEqual(v46StaffExcelRow(staff[0][1]),row);
assert.equal(staff[0][1].authUid,undefined);
await assert.rejects(importNewStaff(args),/Duplicate/);
await assert.rejects(importNewStaff({...args,cells:[V46_STAFF_EXCEL_HEADERS,['ABC',...row.slice(1)],['abc',...row.slice(1)]]}),/valid rows/);
assert.equal([...docs].filter(([p])=>p.startsWith(base+'/staff/')).length,1);
console.log('PASS new Staff XLSX save: all eleven fields, tenant admin, no accounts, duplicate and missing ID denied');
