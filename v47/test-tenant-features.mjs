import assert from 'node:assert/strict';
import {validateTeacherWrite} from './teacher-write-contract.mjs';
import {planTenantQuery} from './tenant-query-plan.mjs';
import {prepareSchoolActivation} from './school-activation.mjs';
import {prepareMembershipActivation} from './membership-activation.mjs';
import {selectTenantSession,assertSessionSchool} from './tenant-session.mjs';
import {roleCapabilities} from './role-capabilities.mjs';
import {studentDocument,markDocument,attendanceDocument,staffDocument} from './tenant-data-model.mjs';
import {auditDocument} from './tenant-audit-path.mjs';
const schoolId='school_A';
assert.equal(validateTeacherWrite({schoolId,studentId:'student_1',className:'Class 10',subject:'Science',marks:{theory:0}}).marks.theory,0);
assert.throws(()=>validateTeacherWrite({schoolId,studentId:'../x',className:'10',subject:'Science',marks:{theory:10}}),TypeError);
assert.throws(()=>validateTeacherWrite({schoolId,studentId:'student_1',className:'10',subject:'Science',marks:{theory:-1}}),RangeError);
assert.equal(planTenantQuery({schoolId,collection:'students',limit:1000}).limit,100);
assert.throws(()=>planTenantQuery({schoolId,collection:'user_roles'}),TypeError);
assert.throws(()=>planTenantQuery({schoolId,collection:'marks',lastDocumentId:'../x'}),TypeError);
assert.throws(()=>prepareSchoolActivation(schoolId,false));
assert.equal(prepareSchoolActivation(schoolId,true).patch.active,true);
assert.throws(()=>prepareMembershipActivation({schoolId,uid:'user_0001',role:'teacher',confirmed:false}));
assert.equal(prepareMembershipActivation({schoolId,uid:'user_0001',role:'teacher',confirmed:true}).data.active,true);
const session=selectTenantSession([{schoolId,role:'viewer',active:true}],schoolId);
assert.equal(assertSessionSchool(session,schoolId),schoolId);
assert.throws(()=>assertSessionSchool(session,'school_B'));
assert.equal(roleCapabilities('viewer').marksWrite,false);
assert.equal(roleCapabilities('teacher').marksWrite,false);
assert.equal(roleCapabilities('school_admin').manage,true);
assert.throws(()=>validateTeacherWrite({schoolId,studentId:'student_1',className:'10',subject:'Science',marks:{}}),TypeError);
assert.throws(()=>planTenantQuery({schoolId,collection:'audit_logs'}),TypeError);
assert.equal(session.authorization,'unverified-client-selection');
assert.throws(()=>roleCapabilities('super_admin'));
assert.equal(studentDocument(schoolId,'student_1'),'schools/school_A/students/student_1');
assert.equal(markDocument(schoolId,'mark_1'),'schools/school_A/marks/mark_1');
assert.equal(attendanceDocument(schoolId,'att_1'),'schools/school_A/attendance/att_1');
assert.equal(staffDocument(schoolId,'staff_1'),'schools/school_A/staff/staff_1');
assert.equal(auditDocument(schoolId,'event_1'),'schools/school_A/audit_logs/event_1');
console.log('V47 tenant feature unit checks passed');
