import assert from 'node:assert/strict';
import {validateTeacherAccountRows,provisionTeacherAccountBatch,TEACHER_ACCOUNT_HEADERS} from './teacher-account-excel.mjs';
const header=TEACHER_ACCOUNT_HEADERS, one=['Teacher One','ONE@example.invalid','example-test-password'],two=['Teacher Two','two@example.invalid','second-test-password'];
const rows=validateTeacherAccountRows([header,one,two]);
assert.equal(rows[0].email,'one@example.invalid');
assert.throws(()=>validateTeacherAccountRows([header,one,['Duplicate','one@example.invalid','duplicate-test-password']]),/दोहोरिएको/);
assert.throws(()=>validateTeacherAccountRows([header,['Short','short@example.invalid','short']]));
assert.throws(()=>validateTeacherAccountRows([['Email','Name','Password'],one]));
assert.throws(()=>validateTeacherAccountRows([header,...Array(26).fill(one)]));
assert.throws(()=>validateTeacherAccountRows([header,['','','']]));
const actor={role:'school_admin',active:true,schoolId:'12345',uid:'admin123'},events=[],reports=[];
const args={rows,actor,schoolId:'12345',assertCurrent:()=>{},verifyPrivilege:async()=>events.push('verify'),createAccount:async({email,role})=>{assert.equal(role,'teacher');events.push('auth');return {uid:'uid_'+email.split('@')[0],accountCreated:true,membershipCreated:false}},addMember:async({uid,role})=>{events.push('member');return {uid,role,schoolId:'12345',active:false}},onResult:r=>reports.push(r)};
assert.deepEqual(await provisionTeacherAccountBatch(args),{created:2,stopped:false,remaining:0});
assert.deepEqual(events,['verify','auth','verify','member','verify','auth','verify','member']);
assert.ok(reports.every(r=>r.status==='inactive'&&!('password' in r)));
await assert.rejects(provisionTeacherAccountBatch({...args,schoolId:'99999'}));
await assert.rejects(provisionTeacherAccountBatch({...args,actor:{...actor,role:'viewer'}}));
events.length=0;reports.length=0;
assert.deepEqual(await provisionTeacherAccountBatch({...args,addMember:async()=>{throw Error('test secret must not leak')}}),{created:0,stopped:true,remaining:1});
assert.deepEqual(events,['verify','auth','verify']);
assert.equal(reports[0].status,'check');assert.equal(reports[0].uid,'uid_one');assert.ok(!JSON.stringify(reports).includes('test secret'));
events.length=0;let checks=0;
await assert.rejects(provisionTeacherAccountBatch({...args,assertCurrent:()=>{if(++checks>2)throw Error('changed session')}}));
assert.deepEqual(events,['verify','auth']);
console.log('V47 teacher Excel validation, tenant guard, sequential inactive creation and partial failure checks passed');
