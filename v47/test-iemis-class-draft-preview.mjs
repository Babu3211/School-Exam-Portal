import assert from 'node:assert/strict';
import {inspectIemisClassDraft} from './iemis-class-draft-preview.mjs';
const students=[{id:'s1'},{id:'s2'},{id:'s3'}],valid={values:{count:'10',obtained:'35'},isAbsent:false,incompatible:false};
const args={classNo:'1',term:'1st',subject:'English',students};
const good=inspectIemisClassDraft({...args,drafts:{s1:valid,s2:valid,s3:valid}});
assert.deepEqual(good,{complete:true,total:3,missing:[],invalid:[]});
const missing=inspectIemisClassDraft({...args,drafts:{s1:valid,s2:valid}});
assert.deepEqual(missing.missing,['s3']);assert.equal(missing.complete,false);
const bad=inspectIemisClassDraft({...args,drafts:{s1:valid,s2:{...valid,values:{count:'10',obtained:'50'}},s3:valid}});
assert.deepEqual(bad.invalid.map(x=>x.studentId),['s2']);assert.equal(bad.complete,false);
const unsupported=inspectIemisClassDraft({...args,term:'weekly',drafts:{s1:valid,s2:valid,s3:valid}});
assert.equal(unsupported.complete,false);assert.equal(unsupported.invalid.length,3);
assert.throws(()=>inspectIemisClassDraft({...args,students:[],drafts:{}}),/complete class roster/);
assert.throws(()=>inspectIemisClassDraft({...args,students:[{id:'s1'},{id:'s1'}],drafts:{}}),/duplicate/);
assert.throws(()=>inspectIemisClassDraft({...args,students:[{id:''}],drafts:{}}),/invalid/);
assert.throws(()=>inspectIemisClassDraft({...args,drafts:[]}),/Class marks drafts/);
assert.equal(inspectIemisClassDraft({...args,drafts:Object.create({s1:valid,s2:valid,s3:valid})}).complete,false);
assert.throws(()=>inspectIemisClassDraft({...args,students:[{id:'x'.repeat(129)}],drafts:{}}),/invalid/);
assert.throws(()=>inspectIemisClassDraft({...args,students:Array.from({length:1501},(_,i)=>({id:'s'+i})),drafts:{}}),/complete class roster/);
assert.throws(()=>inspectIemisClassDraft({...args,drafts:{s1:valid,s2:valid,s3:valid,outsider:valid}}),/outside the selected class roster/);
for(const id of ['../other','student/name','student name','x.y','x\\\\y'])assert.throws(()=>inspectIemisClassDraft({...args,students:[{id}],drafts:{}}),/invalid/);
const secondary={classNo:'9',term:'final',subject:'Computer Science',students:[{id:'s1'},{id:'s2'}]};
const completeComputer={values:{participation:'4',practical:'36',term:'10',theory:'50'},isAbsent:false,incompatible:false};
assert.equal(inspectIemisClassDraft({...secondary,drafts:{s1:completeComputer,s2:completeComputer}}).complete,true);
const missingTheory={...completeComputer,values:{...completeComputer.values,theory:''}};
assert.deepEqual(inspectIemisClassDraft({...secondary,drafts:{s1:completeComputer,s2:missingTheory}}).invalid.map(x=>x.studentId),['s2']);
const symbolDrafts={s1:valid,s2:valid,s3:valid};symbolDrafts[Symbol('foreign')]=valid;
assert.throws(()=>inspectIemisClassDraft({...args,drafts:symbolDrafts}),/unsupported symbol keys/);
const hiddenDrafts={s1:valid,s2:valid,s3:valid};Object.defineProperty(hiddenDrafts,'foreign',{value:valid,enumerable:false});
assert.throws(()=>inspectIemisClassDraft({...args,drafts:hiddenDrafts}),/outside the selected class roster/);
console.log('V47 offline IEMIS class-wide draft completeness tests passed');
