import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {grade9GridLibrary} from './cdc-grade9-grid-library.mjs';
const read=p=>JSON.parse(readFileSync(new URL(p,import.meta.url),'utf8'));
const register=read('./cdc-grade9-source-register-pinned.json');
assert.equal(register.schemaVersion,1);
assert.equal(register.sources.length,40);
assert.ok(register.sources.every(s=>s.grades.includes(9)));
const library=grade9GridLibrary(register);
assert.equal(library.length,11);
assert.equal(new Set(library.map(s=>s.key)).size,11);
assert.ok(library.every(s=>s.currentCdcExactApproved===false&&s.readyForLive===false));
assert.ok(library.every(s=>s.sources.every(x=>/^https:\/\/(?:www\.moecdc\.gov\.np|moecdc\.gov\.np|lib\.moecdc\.gov\.np|giwmscdnone\.gov\.np|giwmscdntwo\.gov\.np)\//.test(x.url))));
const computer=library.find(s=>s.key==='optional_computer'),math=library.find(s=>s.key==='optional_math');
assert.equal(computer.fullMarks,50);assert.equal(math.fullMarks,75);
assert.ok(computer.tables.length>=2);assert.ok(math.tables.length>=3);
assert.ok(library.find(s=>s.key==='science').status.includes('Historical'));
assert.ok(library.find(s=>s.key==='math').status.includes('Historical'));
assert.ok(library.find(s=>s.key==='optional_environment').status.includes('unavailable'));
assert.ok(grade9GridLibrary({sources:[{grades:[9],subject:'English',kind:'specification_grid',url:'javascript:alert(1)'}]}).every(s=>s.sources.every(x=>!x.url.startsWith('javascript:'))));
console.log('PASS V47 Grade 9 Grid Library: 11 subjects, 40 preserved source records, no false official approval, historical and missing grid warnings');
