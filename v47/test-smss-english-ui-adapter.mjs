import assert from 'node:assert/strict';
import {englishClassLabel,englishTermLabel,makeEnglishOptions,standardClassOptions,standardTermOptions,applyEnglishSelectLabels,nepaliActionNotice} from './smss-english-ui-adapter.mjs';
assert.equal(englishClassLabel('कक्षा ६'),'Class 6');
assert.equal(englishClassLabel('कक्षा १२'),'Class 12');
assert.equal(englishClassLabel('Nursery'),'ECD');
assert.equal(englishClassLabel('LKG'),'LKG');
assert.equal(englishTermLabel('मासिक'),'Monthly');
assert.equal(englishTermLabel('साप्ताहिक'),'Weekly');
assert.equal(englishTermLabel('वार्षिक'),'Final Term');
assert.equal(englishTermLabel('तेस्रो त्रैमासिक'),'3rd Term');
assert.equal(standardClassOptions().length,15);
assert.equal(standardTermOptions().length,6);
const options=makeEnglishOptions(['कक्षा १','कक्षा ९']);
assert.deepEqual(options.map(x=>x.value),['कक्षा १','कक्षा ९']);
assert.deepEqual(options.map(x=>x.label),['Class 1','Class 9']);
const select={options:[{value:'कक्षा ६',textContent:'कक्षा ६'},{value:'',textContent:'Select Class'}]};
applyEnglishSelectLabels(select);
assert.equal(select.options[0].value,'कक्षा ६');
assert.equal(select.options[0].textContent,'Class 6');
assert.equal(select.options[1].textContent,'Select Class');
assert.match(nepaliActionNotice('deleteConfirm'),/निश्चित/);
assert.match(nepaliActionNotice('importConfirm',{count:3}),/३|3/);
console.log('PASS: English-only UI labels preserve stored V46 values; notices remain Nepali');
