import assert from 'node:assert/strict';
import {createVerifiedTenantContext} from './verified-tenant-context.mjs';
const sid='12345678',uid='user12345';
const auth={currentUser:{uid}};
const school={id:sid,active:true};
const member={uid,schoolId:sid,role:'school_admin',active:true};
const readDocument=async path=>path==='schools/'+sid?school:path==='schools/'+sid+'/members/'+uid?member:null;
const make=opts=>createVerifiedTenantContext({schoolId:sid,auth,readDocument,...opts});
const ctx=await make();
assert.deepEqual(ctx.collectionSegments('students'),['schools',sid,'students']);
assert.deepEqual(ctx.documentSegments('marks','mark_123'),['schools',sid,'marks','mark_123']);
assert.equal(ctx.assertWrite().role,'school_admin');
assert.equal((await ctx.revalidateWrite()).role,'school_admin');
const revoked=await make({readDocument:async path=>path==='schools/'+sid?school:{...member,active:false}}).catch(()=>null);
assert.equal(revoked,null);
assert.throws(()=>ctx.collectionSegments('members'),/Unreviewed V47 tenant collection/);
assert.throws(()=>ctx.collectionSegments('../students'),/Unreviewed V47 tenant collection/);
assert.throws(()=>ctx.documentSegments('students','../escape'),/Invalid document ID/);
assert.throws(()=>ctx.documentSegments('students',''),/Invalid document ID/);
assert.throws(()=>ctx.documentSegments('students',42),/Invalid document ID/);
assert.equal(Object.isFrozen(ctx),true);
await assert.rejects(make({schoolId:'wrong'}),/IEMIS|School ID/);
await assert.rejects(make({readDocument:async()=>null}),/School unavailable/);
await assert.rejects(make({readDocument:async p=>p==='schools/'+sid?school:null}),/Membership unavailable/);
await assert.rejects(make({readDocument:async p=>p==='schools/'+sid?school:{...member,schoolId:'87654321'}}),/Membership unavailable/);
await assert.rejects(make({readDocument:async p=>p==='schools/'+sid?school:{...member,active:false}}),/Membership unavailable/);
await assert.rejects(make({readDocument:async p=>p==='schools/'+sid?school:{...member,role:'super_admin'}}),/Membership unavailable/);
const viewer=await make({readDocument:async p=>p==='schools/'+sid?school:{...member,role:'viewer'}});
assert.deepEqual(viewer.collectionSegments('students'),['schools',sid,'students']);
assert.throws(()=>viewer.assertWrite(),/School Admin permission required/);
const teacher=await make({readDocument:async p=>p==='schools/'+sid?school:{...member,role:'teacher'}});
assert.throws(()=>teacher.assertWrite(),/School Admin permission required/);
auth.currentUser={uid:'otherUser'};
assert.throws(()=>ctx.collectionSegments('students'),/Authentication changed/);
assert.throws(()=>ctx.assertWrite(),/Authentication changed/);
auth.currentUser={uid};
await assert.rejects(make({readDocument:async p=>{auth.currentUser={uid:'otherUser'};return p==='schools/'+sid?school:member}}),/Authentication changed/);
console.log('Verified V47 tenant context tests passed');
