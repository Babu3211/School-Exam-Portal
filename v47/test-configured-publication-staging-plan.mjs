import assert from 'node:assert/strict';
import {planConfiguredPublicationStaging,verifyConfiguredPublicationStagingPlan} from './configured-publication-staging-plan.mjs';
const schoolId='12345',classId='9',subjectId='computer',examId='final';
const actor={uid:'admin1',active:true,role:'school_admin',schoolId};
const settings={active:true,schoolId,classId,subjectId,examId,components:[{key:'theory',name:'Theory',fullMarks:63},{key:'practical',name:'Practical',fullMarks:37}]};
const ids=Array.from({length:1500},(_,i)=>'s'+String(i).padStart(4,'0'));
const drafts=ids.map(studentId=>({studentId,values:{theory:63,practical:37}}));
const base={actor,settings,schoolId,classId,subjectId,examId,expectedStudentIds:ids,drafts};
const a=planConfiguredPublicationStaging(base);
const b=planConfiguredPublicationStaging({...base,expectedStudentIds:[...ids].reverse(),drafts:[...drafts].reverse()});
assert.deepEqual(a,b);
assert.equal(a.rosterCount,1500);
assert.equal(a.batches.length,15);
assert.deepEqual(a.batches.map(batch=>batch.count),Array(15).fill(100));
assert.equal(a.batches[0].firstStudentId,'s0000');
assert.equal(a.batches.at(-1).lastStudentId,'s1499');
assert.equal(a.writeAuthorized,false);
assert.equal(a.publicationAllowed,false);
assert.equal(a.stagingOnly,true);
assert.equal(Object.isFrozen(a.batches[0].entries[0].values),true);
assert.throws(()=>planConfiguredPublicationStaging({...base,drafts:drafts.slice(1)}),/Complete verified class review required/);
assert.throws(()=>planConfiguredPublicationStaging({...base,actor:{...actor,role:'viewer'}}),/Verified school admin required/);
assert.throws(()=>planConfiguredPublicationStaging({...base,schoolId:'67890'}),/Verified school admin required/);
assert.throws(()=>planConfiguredPublicationStaging({...base,expectedStudentIds:[...ids,'s1500']}),/Complete authoritative class roster required/);
const absent=planConfiguredPublicationStaging({...base,expectedStudentIds:['s0'],drafts:[{studentId:'s0',isAbsent:true}]});
assert.equal(absent.batches[0].entries[0].values,null);
assert.equal(absent.batches[0].entries[0].totalObtained,0);
