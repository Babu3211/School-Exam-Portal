import assert from 'node:assert/strict';
import {importV46PreparedRowsToSchool} from './v46-prepared-import-adapter.mjs';
const uid='firebaseUID123',schoolId='001234567',auth={currentUser:{uid}};
const docs={'schools/001234567':{id:schoolId,active:true},['schools/'+schoolId+'/members/'+uid]:{uid,schoolId,role:'school_admin',active:true}};
const readDocument=async path=>docs[path]??null;
let writes=[];
const writeRecords=async data=>{writes.push(data)};
const base={auth,schoolId,collection:'students',prepared:[{studentName:'Test',studentIemisNo:'00123'}],readDocument,writeRecords};
const result=await importV46PreparedRowsToSchool(base);
assert.equal(result.count,1);
assert.deepEqual(writes[0].path,['schools','001234567','students']);
assert.equal(writes[0].records[0].schoolId,'001234567');
assert.equal(writes[0].records[0].studentIemisNo,'00123');
writes=[];
await assert.rejects(importV46PreparedRowsToSchool({...base,prepared:[{studentName:'ok'},{schoolId:'009876543',studentName:'bad'}]}),/Cross-school/);
assert.equal(writes.length,0,'Mixed-school import must never call writer');
await assert.rejects(importV46PreparedRowsToSchool({...base,schoolId:'009876543'}),/School unavailable/);
assert.equal(writes.length,0);
await assert.rejects(importV46PreparedRowsToSchool({...base,collection:'audit_logs'}),/Unreviewed/);
assert.equal(writes.length,0);
await assert.rejects(importV46PreparedRowsToSchool({...base,prepared:[]}),/Prepared/);
assert.equal(writes.length,0);
console.log('PASS: V46 prepared Excel records use verified V47 school path; rejected imports make zero writer calls');
