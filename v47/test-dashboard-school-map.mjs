import assert from 'node:assert/strict';
import {schoolSatelliteMapLinks} from './dashboard-school-map.mjs';
const schoolId='300160003',school={nameEnglish:'A & B <School>',addressEnglish:'Dhunibesi-05, Dhading'};
const map=schoolSatelliteMapLinks({schoolId,profile:school});
assert.ok(map);
assert.equal(map.query,'A & B <School>, Dhunibesi-05, Dhading, Nepal');
const embed=new URL(map.embedUrl),open=new URL(map.openUrl);
assert.equal(embed.origin,'https://maps.google.com');
assert.equal(open.origin,'https://www.google.com');
assert.equal(embed.searchParams.get('t'),'k');
assert.equal(embed.searchParams.get('q'),map.query);
assert.equal(open.searchParams.get('query'),map.query);
assert.equal(embed.searchParams.get('output'),'embed');
assert.equal(schoolSatelliteMapLinks({schoolId,profile:{...school,addressEnglish:''}}),null);
assert.equal(schoolSatelliteMapLinks({schoolId,profile:{...school,nameEnglish:''}}),null);
assert.equal(schoolSatelliteMapLinks({schoolId,profile:{...school,addressEnglish:'Bad\u0001'}}),null);
assert.throws(()=>schoolSatelliteMapLinks({schoolId:'school_001',profile:school}),/school|IEMIS|ID/i);
const locale=schoolSatelliteMapLinks({schoolId,profile:{nameNepali:'विद्यालय',addressNepali:'धादिङ'}});
assert.ok(locale);assert.match(locale.query,/विद्यालय/);
assert.equal(locale.query.includes('[object Object]'),false);
const {readFileSync}=await import('node:fs');
const html=readFileSync(new URL('./index.html',import.meta.url),'utf8');
const src=readFileSync(new URL('./dashboard-console.mjs',import.meta.url),'utf8');
for(const id of ['schoolMapSection','schoolMapLoad','schoolMapFrame','schoolMapOpen','schoolMapMessage'])
 assert.ok(html.includes('id="'+id+'"'),'Map control absent: '+id);
assert.match(html,/id="schoolMapFrame"[^>]*hidden[^>]*loading="lazy"/);
assert.match(html,/id="schoolMapFrame"[^>]*referrerpolicy="no-referrer"/);
assert.doesNotMatch(html,/src="https:\/\/maps\.google/,'No third-party map request before user click');
assert.match(src,/schoolSatelliteMapLinks/);
assert.match(src,/\$\('schoolMapLoad'\)\.onclick=async/);
assert.match(src,/verifySchoolSession\(\{schoolId:selected\.schoolId,uid:selected\.uid,readDocument\}\)/);
assert.match(src,/\$\('schoolMapFrame'\)\.removeAttribute\('src'\)/);
assert.match(src,/\$\('schoolMapFrame'\)\.src=selected\.map\.embedUrl/);
console.log('PASS school-scoped satellite search uses verified profile, explicit click, and logout reset');
