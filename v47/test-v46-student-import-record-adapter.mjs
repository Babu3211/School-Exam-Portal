import assert from 'node:assert/strict';
import {previewAgainstSchoolStudents} from './verified-student-import-preview.mjs';
import {prepareVerifiedStudentSave} from './verified-student-import-save-gate.mjs';
import {planStudentImportTransaction} from './student-import-transaction-plan.mjs';
import {adaptVerifiedV46StudentImport} from './v46-student-import-record-adapter.mjs';
const schoolId='300160003',uid='admin-1',auth={currentUser:{uid}};
const rows=[{'IEMIS Code':schoolId,'Student IEMIS Id':'00001','Admission Number':'A-01','Student Name':'Student A','Class':'Nursery','Father Name':'Parent A','Permanent Address':'Kathmandu'}];
const readDocument=async path=>path==='schools/'+schoolId?{id:schoolId,active:true}:path==='schools/'+schoolId+'/members/'+uid?{uid,schoolId,role:'school_admin',active:true}:null;
const verifiedPreview=await previewAgainstSchoolStudents({auth,schoolId,rows,readDocument,readStudents:async()=>[]});
const prepared=await prepareVerifiedStudentSave({auth,schoolId,rows,verifiedPreview,confirmed:true,readDocument});
const plan=planStudentImportTransaction({prepared,existingStudents:[]});
const [student]=adaptVerifiedV46StudentImport(plan);
assert.equal(student.class,'ECD');
assert.equal(student.name,'Student A');
assert.equal(student.studentIemisId,'00001');
assert.equal(student.admissionNo,'A-01');
assert.equal(student.fatherName,'Parent A');
assert.equal(student.permanentAddress,'Kathmandu');
assert.equal(student.schoolId,schoolId);
assert.equal(rows[0].schoolId,undefined);
assert.equal(Object.isFrozen(student),true);
assert.throws(()=>adaptVerifiedV46StudentImport({...plan}),/Verified create-only/);
console.log('PASS: authenticated V46 Excel records map to school-scoped V47 schema without writes');
