import assert from 'node:assert/strict';
import {assertV47ImportContext,attachV47SchoolId} from './v46-import-school-gate.mjs';
const session={authorization:'firestore-verified-read',uid:'teacher-uid',schoolId:'001234567',role:'school_admin'};
const ctx=assertV47ImportContext({session,schoolId:'001234567',collection:'students'});
assert.deepEqual(ctx.path,['schools','001234567','students']);
assert.equal(attachV47SchoolId({studentName:'Test'},ctx).schoolId,'001234567');
assert.throws(()=>attachV47SchoolId({studentName:'Test'},{schoolId:'001234567',collection:'students'}),/Verified import context/);
assert.throws(()=>attachV47SchoolId({studentName:'Test'},{...ctx}),/Verified import context/);
assert.ok(Object.isFrozen(ctx.path),'School-scoped path must not be mutable');
assert.throws(()=>attachV47SchoolId({schoolId:'009876543'},ctx),/Cross-school/);
assert.throws(()=>assertV47ImportContext({session,schoolId:'009876543',collection:'students'}),/Cross-school/);
assert.throws(()=>assertV47ImportContext({session:{...session,role:'viewer'},schoolId:'001234567',collection:'students'}),/administrators/);
assert.throws(()=>assertV47ImportContext({session:{...session,role:'teacher'},schoolId:'001234567',collection:'staff'}),/administrators/);
assert.throws(()=>assertV47ImportContext({session:{...session,authorization:'unverified'},schoolId:'001234567',collection:'students'}),/Verified/);
assert.throws(()=>assertV47ImportContext({session,schoolId:'001234567',collection:'user_roles'}),/Unreviewed/);
assert.throws(()=>assertV47ImportContext({session,schoolId:'',collection:'students'}),/Valid/);
console.log('PASS: V47 bulk import school isolation, roles and verification preflight');
