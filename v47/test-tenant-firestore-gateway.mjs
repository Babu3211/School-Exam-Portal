import assert from 'node:assert/strict';
import {tenantReadPlan,tenantListPlan,tenantWritePlan} from './tenant-firestore-gateway.mjs';
const schoolId='12345678',uid='admin_123';
const admin=Object.freeze({schoolId,uid,role:'school_admin',authorization:'firestore-verified-read'});
const viewer=Object.freeze({...admin,role:'viewer'});
const teacher=Object.freeze({...admin,role:'teacher'});
const base={schoolId,uid,collection:'students',id:'student_1'};
assert.equal(tenantReadPlan({...base,session:viewer}).path,'schools/12345678/students/student_1');
assert.equal(tenantListPlan({...base,session:teacher}).path,'schools/12345678/students');
assert.equal(tenantReadPlan({...base,session:admin}).requiresFirestoreRules,true);
const create=tenantWritePlan({...base,session:admin,operation:'create',data:{name:'A'}});
assert.equal(create.data.schoolId,schoolId);
assert.equal(create.data.name,'A');
assert.equal(tenantWritePlan({...base,session:admin,operation:'update',data:{name:'B'}}).operation,'update');
assert.throws(()=>tenantWritePlan({...base,session:viewer,operation:'create',data:{name:'A'}}));
assert.throws(()=>tenantWritePlan({...base,session:teacher,operation:'create',data:{name:'A'}}));
assert.throws(()=>tenantWritePlan({...base,session:admin,operation:'delete',data:{name:'A'}}));
assert.throws(()=>tenantWritePlan({...base,session:admin,operation:'create',data:{schoolId:'87654321'}}));
assert.throws(()=>tenantWritePlan({...base,session:admin,operation:'update',data:{schoolId:'12345678'}}));
assert.throws(()=>tenantWritePlan({...base,session:admin,operation:'create',data:[]}));
assert.throws(()=>tenantReadPlan({...base,session:{...admin,authorization:'unverified-client-selection'}}));
assert.throws(()=>tenantReadPlan({...base,session:admin,schoolId:'87654321'}));
assert.throws(()=>tenantReadPlan({...base,session:admin,uid:'other_123'}));
assert.throws(()=>tenantReadPlan({...base,session:admin,collection:'members'}));
assert.throws(()=>tenantListPlan({...base,session:admin,collection:'audit_logs'}));
assert.throws(()=>tenantWritePlan({...base,session:admin,collection:'members',operation:'create',data:{name:'A'}}));
assert.throws(()=>tenantReadPlan({...base,session:admin,id:'../bad'}));
console.log('V47 tenant Firestore gateway plans passed');
