for(const id of ['schoolId','email','password','login','logout','settings','iemis','name','active','role','message','nameEnglish','nameNepali','addressEnglish','addressNepali','saveProfile']){
 assert.match(html,new RegExp('id="'+id+'"'),'Missing school-settings control '+id);
}
assert.match(html,/id="saveProfile" disabled hidden/);
assert.match(html,/IEMIS ID and activation are managed by the Super Admin/);
assert.doesNotMatch(html,/id="config"/,'School settings must not require pasting Firebase configuration');
assert.match(js,/connectSchoolFirebase/);
assert.match(firebaseClient,/V47_FIREBASE_CONFIG\.projectId!=='smss-exam-portal-v47'/);
assert.match(firebaseClient,/browserSessionPersistence/);
assert.match(js,/authSdk\.onAuthStateChanged\(auth,user=>/);
assert.match(js,/if\(actor&&user\?\.uid!==actor\.uid\)\{reset\(\)/);
assert.match(js,/actor=null;loadedProfile=null/);
assert.match(js,/\$\('schoolId'\)\.disabled=!!actor/);
assert.match(js,/\$\('login'\)\.disabled=!auth\|\|!!actor/);
assert((js.match(/await verifySchoolSession/g)||[]).length>=3,'Reverify school membership for reads and writes');
assert.match(js,/school\.iemisCode!==id/);
assert.match(js,/school\.active!==true/);
assert.match(js,/auth\.currentUser\?\.uid!==uid/);
assert.match(js,/fresh\.role!==session\.role/);
assert.match(js,/\$\('settings'\)\.hidden=false/);
assert.match(js,/canEditSchoolProfile\(session\.role\)/);
assert.match(js,/if\(currentSession\.role!=='school_admin'/);
assert.match(js,/api\.runTransaction\(db,async transaction=>/);
assert.match(js,/transaction\.get\(memberRef/);
assert.match(js,/member\?\.role!=='school_admin'/);
assert.match(js,/member\?\.schoolId!==current\.schoolId/);
assert.match(js,/settings\.schoolId!==current\.schoolId/);
assert.match(js,/profileSignature\(schoolProfileView/);
assert.match(js,/transaction\.set\(profileRef\(current\.schoolId\)/);
assert.doesNotMatch(js,/transaction\.set\(registryRef/,'School registry and IEMIS identity must not be edited');
assert.doesNotMatch(js,/deleteDoc\(|transaction\.delete\(/,'School profile cannot be deleted');
assert.match(rules,/collection in \['staff','classes','school_settings'\] && canAdmin\(sid\)/);
