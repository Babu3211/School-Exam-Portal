import assert from 'node:assert/strict';
import {previewV46PrimaryAchievementSettings} from './preview-v46-primary-achievement-settings.mjs';
const legacy={classGroup:'1-3',className:'1',subject:'Math',components:[{name:'No. of Learning Achievement',fullMarks:3},{name:'Full Marks',fullMarks:12},{name:'Obtained Learning Achievement',fullMarks:12}],totalFullMarks:27};
const args={legacy,schoolId:'12345',classId:'1',subjectId:'math',examId:'final',verifiedSubjectName:'Math'};
const valid=previewV46PrimaryAchievementSettings(args);
assert.equal(valid.learningAchievementCount,3);
assert.equal(valid.fullMarks,12);
assert.equal(valid.obtainedAchievementMaximum,12);
assert.equal(valid.writeAuthorized,false);
assert.equal(valid.requiresDedicatedIemisEntry,true);
const zero=previewV46PrimaryAchievementSettings({...args,legacy:{...legacy,components:legacy.components.map(x=>({...x,fullMarks:0})),totalFullMarks:0}});
assert.equal(zero.fullMarks,0);
assert.throws(()=>previewV46PrimaryAchievementSettings({...args,legacy:{...legacy,components:[legacy.components[0],{...legacy.components[1],fullMarks:11},legacy.components[2]]}}),/derived full marks mismatch/);
assert.throws(()=>previewV46PrimaryAchievementSettings({...args,legacy:{...legacy,totalFullMarks:28}}),/legacy total mismatch/);
assert.throws(()=>previewV46PrimaryAchievementSettings({...args,legacy:{...legacy,components:[...legacy.components].reverse()}}),/Invalid primary/);
assert.throws(()=>previewV46PrimaryAchievementSettings({...args,classId:'4'}),/class group mismatch/);
assert.throws(()=>previewV46PrimaryAchievementSettings({...args,examId:''}),/Explicit verified/);
assert.throws(()=>previewV46PrimaryAchievementSettings({...args,verifiedSubjectName:'Science'}),/subject mismatch/);
console.log('V47 primary achievement migration preview tests passed');
