export function referenceWordClassRuns(value){
 const text=String(value??''),runs=[];let cursor=0;
 for(const m of text.matchAll(/\(([\p{Script=Devanagari}]+)\)/gu)){
  if(m.index>cursor)runs.push({text:text.slice(cursor,m.index)});
  runs.push({text:m[1],underline:true});cursor=m.index+m[0].length;
 }
 if(cursor<text.length)runs.push({text:text.slice(cursor)});
 if(runs.filter(r=>r.underline).length!==6)throw Error('Word class requires six marked words');
 return runs;
}
export function referenceMatchingSegments(value){
 const lines=String(value??'').split('\n'),segments=[];let pending=[];
 const flush=()=>{if(pending.length){segments.push({text:pending.join('\n')});pending=[];}};
 for(let i=0;i<lines.length;i++){
  const header=lines[i].trim().match(/^(Column A|समूह ‘क’)\s{2,}(Column B|समूह ‘ख’)$/u);
  if(!header){pending.push(lines[i]);continue;}
  const rows=[];let j=i+1;
  for(;j<lines.length&&lines[j].includes('|');j++){
   const cells=lines[j].split('|').map(x=>x.trim());
   if(cells.length!==2||!cells[1])break;
   rows.push(cells);
  }
  if(rows.length!==6){pending.push(lines[i]);continue;}
  flush();segments.push({matchingRows:[[header[1],header[2]],...rows]});i=j-1;
 }
 flush();return segments;
}
